#!/usr/bin/env bash
# bench/run_scorecard.sh — Flash vs C Grand Prix scorecard generator.
#
# Fairness model (docs/HOW_WE_MEASURED.md):
#   * Flash side: PPU32 modeled DEVICE STEPS from qemu_ppu32 counters
#     (emulation wall-time is never reported — the host runs the model, the
#     model reports device steps at the declared 1 Tstep/s cadence).
#   * C side: element-op count from an instrumented -O2 build — each inner-
#     loop element op = 1 "step" at the same nominal cadence.
#   * Verdicts: WIN if Flash steps < C steps; PARITY within 2x; else OPEN.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$ROOT/.test_bin/bench"; mkdir -p "$BIN"
QEMU="$ROOT/.test_bin/qemu_ppu32"
FLASHZ="${FLASHZ:-$ROOT/flash/toolchain/flashz}"
CC="${CC:-cc}"

"$FLASHZ" "$ROOT/flasht/qemu_ppu32.zag" -o "$QEMU" >/dev/null 2>&1
: > "$BIN/results.txt"

verdict_for() { # fs other -> WIN|PARITY|OPEN
    if [ "$1" -lt "$2" ]; then echo WIN; else
        if [ "$1" -le "$(($2 * 2))" ]; then echo PARITY; else echo OPEN; fi
    fi
}
ratio() { awk "BEGIN{printf \"%.2f\", $1/$2}"; }

for f in "$ROOT"/bench/flash/*.ppu32; do
    n="$(basename "$f" .ppu32)"
    stat="$("$QEMU" "$f" --stat | grep '^stat ')"
    fsteps="$(echo "$stat" | sed 's/.*steps=\([0-9-]*\).*/\1/')"
    fenergy="$(echo "$stat" | sed 's/.*energy=\([0-9-]*\).*/\1/')"

    csteps=""; rsteps=""; psteps=""
    if [ -f "$ROOT/bench/c/$n.c" ]; then
        "$CC" -O2 -o "$BIN/c_$n" "$ROOT/bench/c/$n.c" -lm
        csteps="$("$BIN/c_$n" | grep -o 'steps=[0-9]*' | cut -d= -f2)"
    fi
    if [ -f "$ROOT/bench/rust/$n.rs" ] && command -v rustc >/dev/null; then
        rustc -O -o "$BIN/r_$n" "$ROOT/bench/rust/$n.rs" 2>/dev/null
        rsteps="$("$BIN/r_$n" | grep -o 'steps=[0-9]*' | cut -d= -f2)"
    fi
    if [ -f "$ROOT/bench/python/$n.py" ]; then
        psteps="$(python3 "$ROOT/bench/python/$n.py" | grep -o 'steps=[0-9]*' | cut -d= -f2)"
    fi
    printf "%s|%s|%s|%s|%s|%s\n" "$n" "$fsteps" "$fenergy" "$csteps" "$rsteps" "$psteps" >> "$BIN/results.txt"
done

{
echo "# SCORECARD — Flash (PPU32, modeled device steps) vs C/Rust/Python (element ops)"
echo
echo "| kernel | Flash steps | vs C | vs Rust | vs Python | verdict |"
echo "|--------|------------|------|---------|-----------|---------|"
sort -t'|' -k1 "$BIN/results.txt" | while IFS='|' read -r n fs fe cs rs ps; do
    vc="-"; vr="-"; vp="-"
    [ -n "$cs" ] && vc="$(ratio $cs $fs)x $(verdict_for $fs $cs)"
    [ -n "$rs" ] && vr="$(ratio $rs $fs)x $(verdict_for $fs $rs)"
    [ -n "$ps" ] && vp="$(ratio $ps $fs)x $(verdict_for $fs $ps)"
    worst=WIN
    for v in "${vc##* }" "${vr##* }" "${vp##* }"; do
        [ "$v" = "OPEN" ] && worst=OPEN
        [ "$v" = "PARITY" ] && [ "$worst" != "OPEN" ] && worst=PARITY
    done
    echo "| $n | $fs | $vc | $vr | $vp | $worst |"
done
echo
echo "Flash energy (model) per kernel: see bench results. Go baseline absent (no toolchain on the bench host — OPEN)."
echo "Generated by bench/run_scorecard.sh — see docs/HOW_WE_MEASURED.md"
} > "$ROOT/docs/SCORECARD.md"
cat "$ROOT/docs/SCORECARD.md"
