#!/usr/bin/env bash
# bench/run_scorecard.sh — Flash vs C Grand Prix scorecard generator.
#
# Fairness model (docs/HOW_WE_MEASURED.md):
#   * Flash side: PPU32 modeled DEVICE STEPS from qemu_ppu32 counters
#     (emulation wall-time is never reported — the host runs the model, the
#     model reports device steps at the declared 1 Tstep/s cadence).
#   * C side: element-op count from an instrumented -O2 build — each inner-
#     loop element op = 1 "step" at the same nominal cadence.
#   * Verdicts: WIN if Flash steps < C steps; PARITY within 2x; else OPEN.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$ROOT/.test_bin/bench"; mkdir -p "$BIN"
QEMU="$ROOT/.test_bin/qemu_ppu32"
FLASHZ="${FLASHZ:-$ROOT/flash/toolchain/flashz}"
CC="${CC:-cc}"

"$FLASHZ" "$ROOT/flasht/qemu_ppu32.zag" -o "$QEMU" >/dev/null 2>&1
: > "$BIN/results.txt"

declare -a NAMES MATF MATC
i=0
for f in "$ROOT"/bench/flash/*.ppu32; do
    n="$(basename "$f" .ppu32)"
    stat="$("$QEMU" "$f" --stat | grep '^stat ')"
    fsteps="$(echo "$stat" | sed 's/.*steps=\([0-9-]*\).*/\1/')"
    fenergy="$(echo "$stat" | sed 's/.*energy=\([0-9-]*\).*/\1/')"
    "$CC" -O2 -o "$BIN/$n" "$ROOT/bench/c/$n.c"
    cout="$("$BIN/$n")"
    csteps="$(echo "$cout" | grep -o 'steps=[0-9]*' | cut -d= -f2)"
    printf "%s|%s|%s|%s\n" "$n" "$fsteps" "$fenergy" "$csteps" >> "$BIN/results.txt"
    i=$((i+1))
done

{
echo "# SCORECARD — Flash (PPU32, modeled device steps) vs C (-O2, element ops)"
echo
echo "| kernel | Flash steps | Flash energy (model) | C steps | Flash/C | verdict |"
echo "|--------|------------|----------------------|---------|---------|---------|"
sort -t'|' -k1 "$BIN/results.txt" | while IFS='|' read -r n fs fe cs; do
    ratio="$(awk "BEGIN{printf \"%.2f\", $cs/$fs}")"
    if [ "$fs" -lt "$cs" ]; then v=WIN; else
        big=$((cs * 2))
        if [ "$fs" -le "$big" ]; then v=PARITY; else v=OPEN; fi
    fi
    echo "| $n | $fs | $fe | $cs | ${ratio}x | $v |"
done
echo
echo "Generated by bench/run_scorecard.sh — see docs/HOW_WE_MEASURED.md"
} > "$ROOT/docs/SCORECARD.md"
cat "$ROOT/docs/SCORECARD.md"
